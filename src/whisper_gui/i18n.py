_STATUS_TO_KEY: dict[TrackStatus, str] = {
    TrackStatus.QUEUED: "status.queued",
    TrackStatus.SLICING: "status.slicing",
    TrackStatus.TRANSCRIBING: "status.transcribing",
    TrackStatus.COMPLETED: "status.completed",
    TrackStatus.CANCELLED: "status.cancelled",
    TrackStatus.ERROR: "status.error",
}

_SENTINEL_STATUS_TO_KEY: dict[str, str] = {
    "Ready": "status.ready",
    "Queued": "status.queued",
    "Slicing Audio": "status.slicing",
    "Transcribing": "status.transcribing",
    "Completed": "status.completed",
    "Cancelled": "status.cancelled",
    "Error": "status.error",
}


def get_language() -> str:
    """Return the active application language code ('en' or 'it')."""
    return _active_language


def set_language(lang: str) -> str:
    """Set the active application language ('en' or 'it'), defaulting to 'en' if unknown."""
    global _active_language
    normalized = (lang or "en").strip().lower()
    _active_language = normalized if normalized in TRANSLATIONS else "en"
    return _active_language


def tr(key: str, **kwargs) -> str:
    """Return the localized string for `key` in the active language, formatted with `kwargs`."""
    table = TRANSLATIONS.get(_active_language, TRANSLATIONS["en"])
    template = table.get(key)
    if template is None:
        template = TRANSLATIONS["en"][key]
    return template.format(**kwargs) if kwargs else template


def translate_track_status(status: TrackStatus) -> str:
    """Return the localized label for a TrackStatus enum value."""
    return tr(_STATUS_TO_KEY[status])


def display_track_status(status_message: str, status: TrackStatus) -> str:
    """Translate standard status sentinels while preserving dynamic runtime messages."""
    if not status_message:
        return translate_track_status(status)
    key = _SENTINEL_STATUS_TO_KEY.get(status_message)
    if key is not None:
        return tr(key)
    return status_message
